#!/usr/bin/env python3
# Upload build/avatar_glb/<id>.glb as Model assets under the owner's account (Open Cloud) and write the id registry.
#   ROBLOX_OPEN_CLOUD_KEY + ROBLOX_CREATOR_ID required, except for --dry-run. python3 tools/blender/upload_avatar.py [--dry-run] [<id> ...]
# Sidekick ids (side_*) and boss ids (boss_*) go to SidekickArt.luau, never to the character registry, which is not rewritten when only they are named.
# Display names use the Id only, never a real name (design doc 5). Ids already in avatar_assets.json are skipped.
import json
import os
import subprocess
import sys
import time

import sidekick_art

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
GLB = os.path.join(REPO, "build", "avatar_glb")
LEDGER = os.path.join(HERE, "avatar_assets.json")
API = "https://apis.roblox.com/assets/v1/"


def curl(*args):
	# Key goes through stdin config, never argv.
	cfg = 'header = "x-api-key: %s"\n' % os.environ["ROBLOX_OPEN_CLOUD_KEY"]
	r = subprocess.run(["curl", "-sS", "--max-time", "120", "-K", "-", *args], input=cfg, capture_output=True, text=True)
	if r.returncode != 0:
		raise RuntimeError(r.stderr.strip())
	return json.loads(r.stdout)


def upload(cid):
	req = {
		"assetType": "Model",
		"displayName": "AnimeRun_" + cid,
		"description": "Anime Run runner model",
		"creationContext": {"creator": {"userId": os.environ["ROBLOX_CREATOR_ID"]}},
	}
	op = curl("-X", "POST", API + "assets", "-F", "request=" + json.dumps(req), "-F", f"fileContent=@{os.path.join(GLB, cid + '.glb')};type=model/gltf-binary")
	if "path" not in op:
		raise RuntimeError(f"{cid}: {op}")
	for _ in range(60):
		time.sleep(3)
		st = curl(API + op["path"])
		if st.get("done"):
			if "response" not in st:
				raise RuntimeError(f"{cid}: {st}")
			return st["response"]["assetId"]
	raise RuntimeError(f"{cid}: timed out {op['path']}")


def write_registry(ledger):
	lines = [
		"--!nonstrict",
		"-- Generated by tools/blender/upload_avatar.py: Id -> uploaded runner Model asset and its 6 part sizes (studs).",
		"-- docs/CHARACTER_GACHA_SPEC.md \"Avatar pipeline\". Do not edit by hand.",
		"return {",
	]
	for cid in sorted(c for c in ledger if not sidekick_art.in_art_registry(c)):
		with open(os.path.join(GLB, cid + ".json")) as f:
			sizes = json.load(f)
		parts = ", ".join("%s = Vector3.new(%g, %g, %g)" % (k, *v) for k, v in sorted(sizes.items()))
		lines.append("\t%s = { Asset = %s, Sizes = { %s } }," % (cid, ledger[cid], parts))
	lines.append("}\n")
	with open(os.path.join(REPO, "src", "shared", "CharacterModelAssets.luau"), "w") as f:
		f.write("\n".join(lines))


def main():
	ledger = json.load(open(LEDGER)) if os.path.exists(LEDGER) else {}
	dry = "--dry-run" in sys.argv
	ids = [a for a in sys.argv[1:] if a != "--dry-run"] or sorted(f[:-4] for f in os.listdir(GLB) if f.endswith(".glb"))
	if dry:
		for cid in ids:
			print("DRY", "unchanged" if cid in ledger else "upload", cid, os.path.getsize(os.path.join(GLB, cid + ".glb")), "bytes")
		print("DRY character registry rewritten:", not all(map(sidekick_art.in_art_registry, ids)))
		return
	for cid in ids:
		if cid in ledger:
			continue
		ledger[cid] = upload(cid)
		with open(LEDGER, "w") as f:
			json.dump(ledger, f, indent=1, sort_keys=True)
		print("UPLOADED", cid, ledger[cid], flush=True)
	sidekick_art.write()
	if not all(map(sidekick_art.in_art_registry, ids)):
		write_registry(ledger)


if __name__ == "__main__":
	main()
