#!/usr/bin/env python3
# Uploads assets/characters_avatar/<id>/portrait.png and head.png as Decal assets under the owner's account (Open Cloud),
# keeps the ledger tools/blender/portrait_assets.json (id -> content Hash, Decal id, Image id, and HeadHash, HeadDecal,
# HeadImage; only changed images re-upload) and writes the generated src/shared/CharacterPortraits.luau and
# CharacterHeads.luau. Display names use the Id only, never a real name (design doc 5). Sidekick ids (side_*) go to
# SidekickArt.luau instead: they are not characters.
#   python3 tools/blender/portrait/upload_portraits.py [--dry-run] [<id> ...]
# ROBLOX_OPEN_CLOUD_KEY + ROBLOX_CREATOR_ID required, except for --dry-run: no network, no writes, no key read.
#
# An ImageLabel needs the image id, and Open Cloud hands back the id of a Decal that wraps the image. So each upload is
# resolved: GET the Decal through the asset delivery API (key needs legacy-asset:manage), download the signed location
# (no key: other host), read the Texture url. Only resolved ids reach the registry. A failed resolve keeps the Decal in
# the ledger, so a rerun retries the resolve and spends no upload.
import gzip
import glob
import hashlib
import json
import os
import re
import subprocess
import sys
import time
from urllib.parse import urlparse

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import sidekick_art  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
AVATARS = os.path.join(REPO, "assets", "characters_avatar")
LEDGER = os.path.join(os.path.dirname(HERE), "portrait_assets.json")
# Ledger key prefix, display name part, file, registry, what the registry maps to
KINDS = (
	("", "Portrait", "portrait.png", os.path.join(REPO, "src", "shared", "CharacterPortraits.luau"), "portrait"),
	("Head", "Head", "head.png", os.path.join(REPO, "src", "shared", "CharacterHeads.luau"), "head"),
)
API = "https://apis.roblox.com/assets/v1/"
DELIVERY = "https://apis.roblox.com/asset-delivery-api/v1/assetId/"
TEXTURE = re.compile(rb'name="Texture"[^>]*>\s*<url>[^<]*?(\d+)\s*</url>')


def curl(*args):
	# Key goes through stdin config, never argv.
	cfg = 'header = "x-api-key: %s"\n' % os.environ["ROBLOX_OPEN_CLOUD_KEY"]
	r = subprocess.run(["curl", "-sS", "--max-time", "120", "-K", "-", *args], input=cfg, capture_output=True, text=True)
	if r.returncode != 0:
		raise RuntimeError(r.stderr.strip())
	return json.loads(r.stdout)


def upload(cid, path, title, description=None):
	req = {
		"assetType": "Decal",
		"displayName": f"AnimeRun_{title}_{cid}",
		"description": description or f"Anime Run character {title.lower()}",
		"creationContext": {"creator": {"userId": os.environ["ROBLOX_CREATOR_ID"]}},
	}
	op = curl("-X", "POST", API + "assets", "-F", "request=" + json.dumps(req), "-F", f"fileContent=@{path};type=image/png")
	if "path" not in op:
		raise RuntimeError(f"{cid}: {op}")
	for _ in range(60):
		time.sleep(3)
		st = curl(API + op["path"])
		if st.get("done"):
			if "response" not in st:
				raise RuntimeError(f"{cid}: {st}")
			return st["response"]["assetId"]
	raise RuntimeError(f"{cid}: timed out {op['path']}")


def image_id_in(body):
	"""The image id inside a downloaded Decal asset (an XML model). Raises on anything else rather than guess."""
	if body.startswith(b"\x1f\x8b"):  # the CDN sends the model gzipped
		body = gzip.decompress(body)
	found = TEXTURE.search(body)
	if found:
		return found.group(1).decode()
	if body.startswith(b"\x89PNG"):
		raise RuntimeError("asset delivery returned the raw image, which carries no image id")
	if body.startswith(b"<roblox!"):
		raise RuntimeError("asset delivery returned a binary model: add a binary parser")
	raise RuntimeError(f"no Texture url in {len(body)} bytes starting {body[:40]!r}")


def resolve(cid, decal):
	last = None
	for _ in range(10):  # a fresh asset can take a moment to reach delivery
		st = curl(DELIVERY + str(decal))
		location = st.get("location")
		if location:
			if urlparse(location).scheme != "https":
				raise RuntimeError(f"{cid}: refusing a non-https location")
			# A signed CDN url: no key, no -K, and it never goes to a log or an error message.
			r = subprocess.run(["curl", "-sS", "--fail", "-L", "--max-time", "120", location], capture_output=True)
			if r.returncode != 0:
				raise RuntimeError(f"{cid}: asset download failed with curl exit {r.returncode}")
			return image_id_in(r.stdout)
		last = st
		time.sleep(3)
	raise RuntimeError(f"{cid}: no delivery location for Decal {decal}, a 403 means the key lacks legacy-asset:manage: {last}")


def write_registry(path, what, entries):
	lines = [
		"--!nonstrict",
		f"-- Generated by tools/blender/portrait/upload_portraits.py: Id -> uploaded {what} image. Do not edit by hand.",
		f'-- docs/CHARACTER_GACHA_SPEC.md "Digital art portrait". An Id with no {what} yet is absent.',
		"return {",
	]
	lines += ['\t%s = "rbxassetid://%s",' % (cid, image) for cid, image in sorted(entries.items())]
	lines.append("}\n")
	with open(path, "w") as f:
		f.write("\n".join(lines))


def self_check():
	# Shape from the Decal XML as described on the DevForum; replace it with a real body if the first upload differs.
	sample = b'<Item class="Decal"><Properties><Content name="Texture"><url>http://www.roblox.com/asset/?id=123</url></Content></Properties></Item>'
	assert image_id_in(sample) == "123"
	assert image_id_in(sample.replace(b"http://www.roblox.com/asset/?id=", b"rbxassetid://")) == "123"
	assert image_id_in(gzip.compress(sample)) == "123"
	for bad in (b"\x89PNGxx", b"<roblox!xx", b"<html>id=5</html>"):
		try:
			image_id_in(bad)
		except RuntimeError:
			continue
		raise AssertionError(bad)


def main():
	self_check()
	args = sys.argv[1:]
	dry = "--dry-run" in args
	named = [a for a in args if a != "--dry-run"]
	ledger = json.load(open(LEDGER)) if os.path.exists(LEDGER) else {}
	if not dry:
		for name in ("ROBLOX_OPEN_CLOUD_KEY", "ROBLOX_CREATOR_ID"):
			if name not in os.environ:
				raise SystemExit(name + " is not set")
	rendered = [{os.path.basename(os.path.dirname(p)): p for p in glob.glob(os.path.join(AVATARS, "*", kind[2]))} for kind in KINDS]
	missing = [cid for cid in named if not any(cid in found for found in rendered)]
	if missing:
		raise SystemExit(f"nothing rendered for {missing}")
	for (prefix, title, _, registry, what), found in zip(KINDS, rendered):
		hash_key, decal_key, image_key = prefix + "Hash", prefix + "Decal", prefix + "Image"
		counts = {"upload": 0, "resolve": 0, "unchanged": 0}
		for cid in sorted(cid for cid in (named or found) if cid in found):
			with open(found[cid], "rb") as f:
				digest = hashlib.sha256(f.read()).hexdigest()
			row = ledger.setdefault(cid, {}) if not dry else ledger.get(cid, {})
			action = "upload" if row.get(hash_key) != digest else "resolve" if not row.get(image_key) else "unchanged"
			counts[action] += 1
			if dry:
				print(f"DRY {title} {action:9} {cid} {os.path.getsize(found[cid])} bytes sha256={digest[:12]}")
				continue
			if action == "upload":
				row.pop(image_key, None)  # the old image is out of date; the row's other kind stays
				row[decal_key] = upload(cid, found[cid], title)
				row[hash_key] = digest
				print("UPLOADED", title, cid, row[decal_key], flush=True)
			if action != "unchanged":
				try:
					row[image_key] = resolve(cid, row[decal_key])
				finally:  # every paid upload lands in the ledger, resolved or not
					with open(LEDGER, "w") as f:
						json.dump(ledger, f, indent=1, sort_keys=True)
				print("RESOLVED", title, cid, row[image_key], flush=True)
		# Rendered ids only: a ledger row whose image was deleted drops out.
		entries = {cid: ledger[cid][image_key] for cid in found if ledger.get(cid, {}).get(image_key) and not sidekick_art.is_sidekick(cid)}
		if dry:
			print(f"DRY {title} {counts}; no network, nothing written. Registry now would hold {len(entries)} of {len(found)} rendered ids.")
			continue
		write_registry(registry, what, entries)
		print("REGISTRY", title, len(entries), "of", len(found), "rendered ids")
	if not dry:
		sidekick_art.write()


if __name__ == "__main__":  # upload_boss_vfx.py reuses upload and resolve
	main()
