#!/usr/bin/env python3
# Uploads The Golden King's UI art and his portrait and head (design doc 4.37 "Third boss", BOSS_EVENT_SPEC "The Golden King";
# owner allowed 2026-11-11) as Decals, resolves each to its image id and writes the generated src/shared/BossKingArt.luau.
# His Model asset is not here: upload_avatar.py puts it in SidekickArt.luau as BossModel, as for the Elf Mage.
# Ledger: tools/blender/king_art_assets.json (name -> Hash, Decal, Image). A file whose hash is already in the ledger never uploads
# again; a Decal left by a failed resolve is retried without spending an upload. Only resolved ids reach the Luau.
#   python3 tools/blender/portrait/upload_king_art.py [--dry-run] [<name> ...]     (no names: all 4)
# ROBLOX_OPEN_CLOUD_KEY + ROBLOX_CREATOR_ID required, except for --dry-run: no network, no writes.
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
UI = os.path.join(REPO, "assets", "ui", "boss_king")
AVATAR = os.path.join(REPO, "assets", "characters_avatar", "boss_king")
LEDGER = os.path.join(REPO, "tools", "blender", "king_art_assets.json")
LUAU = os.path.join(REPO, "src", "shared", "BossKingArt.luau")
# name -> (file, Luau field)
ART = {
	"key_icon": (os.path.join(UI, "key_icon.png"), "KeyIcon"),
	"status_fortified": (os.path.join(UI, "status_fortified.png"), "StatusFortified"),
	"portrait": (os.path.join(AVATAR, "portrait.png"), "Portrait"),
	"head": (os.path.join(AVATAR, "head.png"), "Head"),
}


def names_from(args):
	unknown = [a for a in args if a not in ART]
	if unknown:
		raise SystemExit(f"unknown art names: {unknown}")
	return list(dict.fromkeys(args)) or list(ART)


def digest(path):
	with open(path, "rb") as f:
		return hashlib.sha256(f.read()).hexdigest()


def action(row, ledger, h):
	"""upload, resolve or unchanged. A hash already in the ledger (any row) never uploads again."""
	if row.get("Hash") != h and h not in {r.get("Hash") for r in ledger.values()}:
		return "upload"
	return "unchanged" if row.get("Image") else "resolve"


def lines(ledger):
	out = [
		"--!nonstrict",
		"-- Generated by tools/blender/portrait/upload_king_art.py: The Golden King's UI art, portrait and head (image ids). Do not edit by hand.",
		'-- Design doc 4.37 "Third boss", docs/BOSS_EVENT_SPEC.md "The Golden King". A name with no resolved image yet is absent.',
		"return {",
	]
	for name, (_, field) in ART.items():
		if ledger.get(name, {}).get("Image"):
			out.append('\t%s = "rbxassetid://%s",' % (field, ledger[name]["Image"]))
	return out + ["}", ""]


def save(ledger):
	with open(LEDGER, "w") as f:
		json.dump(ledger, f, indent="\t", sort_keys=True)
		f.write("\n")


def self_check():
	assert names_from([]) == list(ART) and names_from(["head", "head"]) == ["head"]
	assert action({}, {}, "a") == "upload" and action({"Hash": "a", "Decal": "1"}, {}, "a") == "resolve"
	assert action({}, {"x": {"Hash": "a"}}, "a") == "resolve" and action({"Hash": "a", "Image": "2"}, {}, "a") == "unchanged"
	assert lines({"head": {"Image": "5"}})[4:] == ['\tHead = "rbxassetid://5",', "}", ""]


def main():
	self_check()
	args = sys.argv[1:]
	dry = "--dry-run" in args
	names = names_from([a for a in args if a != "--dry-run"])
	missing = [n for n in names if not os.path.exists(ART[n][0])]
	if missing:
		raise SystemExit(f"nothing drawn for {missing}")
	ledger = json.load(open(LEDGER)) if os.path.exists(LEDGER) else {}
	if dry:
		for n in names:
			print("DRY", action(ledger.get(n, {}), ledger, digest(ART[n][0])), n, os.path.getsize(ART[n][0]), "bytes")
		return
	for key in ("ROBLOX_OPEN_CLOUD_KEY", "ROBLOX_CREATOR_ID"):
		if key not in os.environ:
			raise SystemExit(key + " is not set")
	# upload_portraits guards its main() and sidekick_art only defines; never import upload_dodge_art.
	sys.path.insert(0, HERE)
	import upload_portraits as up

	try:
		for n in names:
			path = ART[n][0]
			h = digest(path)
			row = ledger.get(n, {})
			step = action(row, ledger, h)
			if step == "unchanged":
				print("SKIP", n, row["Image"], flush=True)
				continue
			if step == "upload":
				row = {"Hash": h, "Decal": up.upload(n, path, "BossKingArt", "Anime Run boss art")}
				ledger[n] = row
				save(ledger)
				print("UPLOADED", n, row["Decal"], flush=True)
			elif not row.get("Decal"):  # the same picture under another name: share its Decal
				twin = next(r for r in ledger.values() if r.get("Hash") == h)
				row = ledger[n] = {k: twin[k] for k in ("Hash", "Decal", "Image") if k in twin}
				save(ledger)
				if row.get("Image"):
					continue
			row["Image"] = up.resolve(n, row["Decal"])
			save(ledger)
			print("RESOLVED", n, row["Image"], flush=True)
	finally:  # every paid upload is in the ledger already; the Luau holds what resolved
		with open(LUAU, "w") as f:
			f.write("\n".join(lines(ledger)))


if __name__ == "__main__":
	main()
