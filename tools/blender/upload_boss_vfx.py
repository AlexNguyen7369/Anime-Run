#!/usr/bin/env python3
# Uploads Big Raga's effect textures (boss_vfx_textures.py) and flat low-graphics images (bake_boss_raga.py images) as Decals and
# resolves their image ids the way upload_portraits.py does. Ledger tools/blender/boss_vfx_assets.json (name -> Hash, Decal, Image;
# only changed images re-upload); writes the generated src/shared/BossVfxArt.luau.
#   python3 tools/blender/upload_boss_vfx.py [--dry-run]
# ROBLOX_OPEN_CLOUD_KEY="$ANIMERUN_OPEN_CLOUD_KEY" + ROBLOX_CREATOR_ID required (handoff: the resolve needs legacy-asset:manage), except for --dry-run.
import glob
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "portrait"))
import upload_portraits as up  # noqa: E402

REPO = os.path.dirname(os.path.dirname(HERE))
ART = os.path.join(REPO, "assets", "characters_avatar", "boss_raga")
LEDGER = os.path.join(HERE, "boss_vfx_assets.json")
REGISTRY = os.path.join(REPO, "src", "shared", "BossVfxArt.luau")


def main():
	dry = "--dry-run" in sys.argv
	ledger = json.load(open(LEDGER)) if os.path.exists(LEDGER) else {}
	files = {os.path.basename(p)[:-4]: p for p in glob.glob(os.path.join(ART, "vfx", "*.png"))}
	files.update({"Flat" + os.path.basename(p)[:-4].capitalize(): p for p in glob.glob(os.path.join(ART, "flat", "*.png"))})
	for name, path in sorted(files.items()):
		digest = hashlib.sha256(open(path, "rb").read()).hexdigest()
		row = ledger.get(name, {})
		if row.get("Hash") == digest and row.get("Image"):
			continue
		if dry:
			print("DRY upload", name, os.path.getsize(path), "bytes")
			continue
		if row.get("Hash") != digest or not row.get("Decal"):
			row = {"Hash": digest, "Decal": up.upload(name, path, "BossVfx")}
		ledger[name] = row
		with open(LEDGER, "w") as f:
			json.dump(ledger, f, indent=1, sort_keys=True)
		row["Image"] = up.resolve(name, row["Decal"])
		with open(LEDGER, "w") as f:
			json.dump(ledger, f, indent=1, sort_keys=True)
		print("UPLOADED", name, row["Image"], flush=True)
	if dry:
		return
	lines = ["--!nonstrict", "-- Generated by tools/blender/upload_boss_vfx.py: Big Raga's effect textures and flat images. Do not edit by hand.", "return {"]
	lines += ['\t%s = "rbxassetid://%s",' % (name, ledger[name]["Image"]) for name in sorted(ledger)]
	with open(REGISTRY, "w") as f:
		f.write("\n".join(lines + ["}\n"]))


main()
