#!/usr/bin/env python3
# Uploads build/plaza/glb/<key>.glb as Model assets under the owner's account (Open Cloud), keeps the id ledger
# tools/blender/plaza/plaza_assets.json (re-uploads a key when its geometry hash changed; a stale id is orphaned) and
# writes the generated src/shared/PlazaAssets.luau. ROBLOX_OPEN_CLOUD_KEY + ROBLOX_CREATOR_ID required.
#   python3 tools/blender/plaza/upload_plaza.py        Run build_plaza.py -- --export first.
import json
import os
import subprocess
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
BUILD = os.path.join(REPO, "build", "plaza")
LEDGER = os.path.join(HERE, "plaza_assets.json")
API = "https://apis.roblox.com/assets/v1/"


def curl(*args):
	# Key goes through stdin config, never argv.
	cfg = 'header = "x-api-key: %s"\n' % os.environ["ROBLOX_OPEN_CLOUD_KEY"]
	r = subprocess.run(["curl", "-sS", "--max-time", "120", "-K", "-", *args], input=cfg, capture_output=True, text=True)
	if r.returncode != 0:
		raise RuntimeError(r.stderr.strip())
	return json.loads(r.stdout)


def upload(key):
	req = {
		"assetType": "Model",
		"displayName": "AnimeRun_Plaza_" + key,
		"description": "Anime Run plaza mesh",
		"creationContext": {"creator": {"userId": os.environ["ROBLOX_CREATOR_ID"]}},
	}
	op = curl("-X", "POST", API + "assets", "-F", "request=" + json.dumps(req), "-F", f"fileContent=@{os.path.join(BUILD, 'glb', key + '.glb')};type=model/gltf-binary")
	if "path" not in op:
		raise RuntimeError(f"{key}: {op}")
	for _ in range(60):
		time.sleep(3)
		st = curl(API + op["path"])
		if st.get("done"):
			if "response" not in st:
				raise RuntimeError(f"{key}: {st}")
			return st["response"]["assetId"]
	raise RuntimeError(f"{key}: timed out {op['path']}")


def v3(v):
	return "Vector3.new(%.3f, %.3f, %.3f)" % tuple(v)


def write_registry(layout, ledger):
	out = [
		"--!nonstrict",
		"-- Generated by tools/blender/plaza/upload_plaza.py from tools/blender/plaza/build_plaza.py (design doc 4.24 and 4.43,",
		"-- WORLD_REDESIGN_SPEC 4 and 7). Do not edit by hand. Part Center / Size are studs in the asset's local frame.",
		"return {",
		"\tAssets = {",
	]
	for key in sorted(layout["Assets"]):
		parts = []
		for name, p in sorted(layout["Assets"][key]["Parts"].items()):
			glow = ', Glow = "%s"' % p["Glow"] if "Glow" in p else ""
			parts.append('%s = { Size = %s, Center = %s%s }' % (name, v3(p["Size"]), v3(p["Center"]), glow))
		out.append("\t\t%s = { Asset = %s, Parts = { %s } }," % (key, ledger[key]["Asset"], ", ".join(parts)))
	out.append("\t},")
	out.append("\tPlaced = {")
	for row in layout["Placed"]:
		out.append('\t\t{ Key = "%s", Pos = %s, Face = Vector3.new(%.4f, 0, %.4f) },' % (row["Key"], v3(row["Pos"]), *row["Face"]))
	out.append("\t},")
	# The Saitamo exclusive pedestal (design doc 4.35, 4.43): Client/PlazaSkyLoop stands the rig here
	e = layout["Exclusive"]
	out.append('\tExclusive = { Id = "%s", Pos = %s, Face = Vector3.new(%.4f, 0, %.4f) },' % (e["Id"], v3(e["Pos"]), *e["Face"]))
	out.append("\tSigns = {")
	for row in layout["Signs"]:
		out.append('\t\t{ Text = "%s", Pos = %s, Face = Vector3.new(%.4f, 0, %.4f), Size = %.2f, Color = "%s" },' % (row["Text"], v3(row["Pos"]), *row["Face"], row["Size"], row["Color"]))
	out.append("\t},")
	out.append("\tLandmarks = {")
	for name, pos in sorted(layout["Landmarks"].items()):
		out.append("\t\t%s = %s," % (name, v3(pos)))
	out.append("\t},")
	out.append("\tLoopRadius = %g," % layout["LoopRadius"])
	out.append("\tLoopHeight = %g," % layout["LoopHeight"])
	out.append("}\n")
	with open(os.path.join(REPO, "src", "shared", "PlazaAssets.luau"), "w") as f:
		f.write("\n".join(out))


def main():
	layout = json.load(open(os.path.join(BUILD, "layout.json")))
	ledger = json.load(open(LEDGER)) if os.path.exists(LEDGER) else {}
	for key, a in sorted(layout["Assets"].items()):
		if ledger.get(key, {}).get("Hash") == a["Hash"]:
			continue
		tris = sum(p["Tris"] for p in a["Parts"].values())
		# A changed mesh loses its signature: the rules auditor reviews it again (BIOME_ENVIRONMENT_SPEC 4.1)
		ledger[key] = {"Hash": a["Hash"], "Asset": upload(key), "Lane": "B", "Kind": "Mesh", "Tris": tris}
		with open(LEDGER, "w") as f:
			json.dump(ledger, f, indent=1, sort_keys=True)
		print("UPLOADED", key, ledger[key]["Asset"], flush=True)
	write_registry(layout, ledger)
	print("REGISTRY", len(layout["Assets"]), "assets; NOT REVIEWED:", [k for k in layout["Assets"] if "Reviewed" not in ledger[k]])


if __name__ == "__main__":
	main()
