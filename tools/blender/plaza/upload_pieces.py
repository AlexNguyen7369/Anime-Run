#!/usr/bin/env python3
# Uploads the spawn pieces of build/plaza/pieces (build_gate_*, build_altar_*, build_market_*, build_loop: piece_export.py) as Model assets
# under the owner's account, keeps their own ledger (plaza_pieces.json) and writes src/shared/PlazaPieceAssets.luau (Asset 0: not
# uploaded, so the game keeps today's plaza there). upload_plaza.py and plaza_assets.json know nothing of them, so a plain run of
# it can never upload an old mesh over a piece or the reverse.
#   python3 tools/blender/plaza/upload_pieces.py [key ...] [--dry] [--registry]
# Keys: only those (default: all but *Draft). --dry lists; --registry writes the table without uploading.
# Everything is read, checked and rendered to text before the first upload. A key whose hash is in the ledger is not sent
# again. ROBLOX_OPEN_CLOUD_KEY + ROBLOX_CREATOR_ID required to upload. Self-check (no network): --self-test
import json
import os
import sys

import upload_plaza as up

LEDGER = os.path.join(up.HERE, "plaza_pieces.json")
FOLDER = os.path.join(up.BUILD, "pieces")
TABLE = os.path.join(up.REPO, "src", "shared", "PlazaPieceAssets.luau")


def load():
	"""key -> piece, of every set's json; raises on a missing or empty GLB, a bad row or a key in two sets."""
	out = {}
	for name in sorted(f for f in os.listdir(FOLDER) if f.endswith(".json")):
		for key, a in json.load(open(os.path.join(FOLDER, name))).items():
			path = os.path.join(FOLDER, key + ".glb")
			if key in out:
				raise SystemExit("%s is in two sets" % key)
			if not os.path.exists(path) or os.path.getsize(path) == 0:
				raise SystemExit("%s: no GLB" % key)
			if not (a.get("Hash") and a.get("Parts") and len(a.get("Pos", ())) == 3 and len(a.get("Face", ())) == 2):
				raise SystemExit("%s: incomplete row" % key)
			out[key] = a
	if not out:
		raise SystemExit("no pieces in %s" % FOLDER)
	return out


def table(pieces, ledger):
	out = [
		"--!nonstrict",
		"-- Generated by tools/blender/plaza/upload_pieces.py (WORLD_REDESIGN_SPEC 4.2). Do not edit by hand. Asset 0: not uploaded, so the",
		"-- game keeps today's plaza there (Shared/PlazaPieces). Part Center / Size are studs in the piece's frame, Pos and Face its place.",
		"return {",
	]
	for key in sorted(pieces):
		a = pieces[key]
		row = ledger.get(key, {})
		out.append("\t%s = {" % key)
		out.append("\t\tAsset = %s," % (row["Asset"] if row.get("Hash") == a["Hash"] else 0))
		out.append('\t\tHash = "%s",' % a["Hash"])
		out.append("\t\tPos = %s," % up.v3(a["Pos"]))
		out.append("\t\tFace = Vector3.new(%.4f, 0, %.4f)," % tuple(a["Face"]))
		out.append("\t\tParts = {")
		for name, p in sorted(a["Parts"].items()):
			glow = ', Glow = "%s"' % p["Glow"] if "Glow" in p else ""
			out.append("\t\t\t%s = { Size = %s, Center = %s%s }," % (name, up.v3(p["Size"]), up.v3(p["Center"]), glow))
		out.extend(["\t\t},", "\t},"])
	out.append("}\n")
	return "\n".join(out)


def wanted(pieces, ledger, names):
	unknown = [n for n in names if n not in pieces]
	if unknown:
		raise SystemExit("unknown: %s" % ", ".join(unknown))
	keys = names or [k for k in sorted(pieces) if not k.endswith("Draft")]
	return [k for k in keys if ledger.get(k, {}).get("Hash") != pieces[k]["Hash"]]


def self_test():
	piece = {"Hash": "h", "Parts": {"Body": {"Size": [1, 2, 3], "Center": [0, 1, 0], "Tris": 1}}, "Pos": [1, 2, 3], "Face": [0, 1]}
	pieces = {"A": piece, "B": dict(piece, Hash="b"), "CDraft": piece}
	assert wanted(pieces, {}, []) == ["A", "B"]
	assert wanted(pieces, {"A": {"Hash": "h", "Asset": 7}}, []) == ["B"]
	assert wanted(pieces, {}, ["CDraft"]) == ["CDraft"]
	assert "Asset = 7," in table(pieces, {"A": {"Hash": "h", "Asset": 7}})
	assert "Asset = 7," not in table(pieces, {"A": {"Hash": "old", "Asset": 7}}), "a stale id is never used"
	try:
		wanted(pieces, {}, ["X"])
	except SystemExit:
		return print("self-test ok")
	raise AssertionError("an unknown key passed")


def main():
	argv = sys.argv[1:]
	if "--self-test" in argv:
		return self_test()
	pieces = load()
	ledger = json.load(open(LEDGER)) if os.path.exists(LEDGER) else {}
	todo = wanted(pieces, ledger, [a for a in argv if not a.startswith("--")])
	text = table(pieces, ledger)  # fails here, not after an upload
	for key in todo:
		print("UPLOAD", key, os.path.getsize(os.path.join(FOLDER, key + ".glb")), "bytes", sum(p["Tris"] for p in pieces[key]["Parts"].values()), "tris", pieces[key]["Hash"])
	if "--dry" in argv:
		return
	if "--registry" not in argv:
		for name in ("ROBLOX_OPEN_CLOUD_KEY", "ROBLOX_CREATOR_ID"):
			if not os.environ.get(name):
				raise SystemExit(name + " is not set")
		if not os.access(os.path.dirname(TABLE), os.W_OK):
			raise SystemExit("cannot write " + TABLE)
		for key in todo:
			a = pieces[key]
			tris = sum(p["Tris"] for p in a["Parts"].values())
			ledger[key] = {"Hash": a["Hash"], "Asset": up.upload(key, FOLDER), "Lane": "B", "Kind": "Mesh", "Tris": tris}
			with open(LEDGER, "w") as f:
				json.dump(ledger, f, indent=1, sort_keys=True)
			print("UPLOADED", key, ledger[key]["Asset"], flush=True)
		text = table(pieces, ledger)
	with open(TABLE, "w") as f:
		f.write(text)
	print("TABLE", len(pieces), "pieces; NOT REVIEWED:", [k for k in ledger if "Reviewed" not in ledger[k]])


if __name__ == "__main__":
	main()
